"""Re-run the dashboard's SQL against BigQuery and rewrite data/data.js.

Usage:
    python scripts/refresh_data.py --project YOUR_GCP_PROJECT_ID

The queries read the public dataset bigquery-public-data.thelook_ecommerce;
the project you pass is only the one billed for running them (about 50 MB
scanned per query, well inside BigQuery's free tier).
"""
import argparse
import datetime
import decimal
import json
import pathlib
import sys

from google.cloud import bigquery

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATASETS = ["kpis", "by_country", "monthly_region", "by_category", "monthly"]


def to_json(value):
    if isinstance(value, decimal.Decimal):
        return float(value)
    if isinstance(value, (datetime.date, datetime.datetime)):
        return value.isoformat()
    raise TypeError(f"Can't serialise {type(value).__name__}")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--project", required=True, help="Google Cloud project billed for the queries")
    args = parser.parse_args()

    client = bigquery.Client(project=args.project)
    data = {
        "generated_at": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
        "source": "bigquery-public-data.thelook_ecommerce",
    }
    for name in DATASETS:
        sql = (ROOT / "sql" / f"{name}.sql").read_text(encoding="utf-8")
        rows = [dict(row) for row in client.query(sql).result()]
        if not rows:
            sys.exit(f"{name}.sql returned no rows; data/data.js was not changed.")
        data[name] = rows
        print(f"{name}: {len(rows)} rows")

    out = ROOT / "data" / "data.js"
    out.write_text(
        "// Generated by scripts/refresh_data.py. Do not edit by hand.\n"
        "window.DASHBOARD_DATA = " + json.dumps(data, indent=1, default=to_json) + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
